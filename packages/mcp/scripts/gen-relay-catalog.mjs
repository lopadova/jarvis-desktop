// Writes packages/relay/src/shared/catalog.generated.ts from @jarvis/core McpTools.
// The relay must stay self-contained (Deploy-to-Cloudflare clones only packages/relay), so it gets a
// generated copy of the tool catalogue instead of a workspace dependency. `test/relay-catalog.test.ts`
// fails when the copy is stale.
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '..', 'relay', 'src', 'shared', 'catalog.generated.ts');

const result = await build({
  stdin: {
    contents: "export { toolDefinitions } from './src/tools.ts';",
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  logLevel: 'error',
});
const code = result.outputFiles[0].text;
const { toolDefinitions } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

const source = `// GENERATED by packages/mcp/scripts/gen-relay-catalog.mjs from @jarvis/core McpTools — do not edit.
// Regenerate with: pnpm --filter @jarvis/mcp gen:relay

export interface CatalogTool {
  name: string;
  title: string;
  description: string;
  inputSchema: { type: 'object'; [key: string]: unknown };
  annotations: {
    title: string;
    readOnlyHint: boolean;
    destructiveHint: boolean;
    idempotentHint: boolean;
    openWorldHint: boolean;
  };
}

export const TOOL_CATALOG: readonly CatalogTool[] = ${JSON.stringify(toolDefinitions(), null, 2)};
`;

await writeFile(target, source);
console.log(`Wrote ${target} (run \`npx biome format --write\` on it to match the repo style)`);
